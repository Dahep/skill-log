#!/usr/bin/env bash
# Build the release-shaped artifact: a binary plus lib/ beside it.
#
#   scripts/build.sh
#
# The artifact runs on a machine with no Mojo toolchain and no system
# SQLite:
#
#   dist/skill-log          the executable, rpath $ORIGIN/lib
#   dist/lib/               the three Mojo runtime libraries + libsqlite3.so.0
#
# The version is baked in at build time from SKILL_LOG_VERSION, else
# `git describe --tags`, else 0.0.0-dev. It is written into a generated
# source file that shadows the checked-in placeholder: the tree's
# `src/skill_log/version.mojo` returns 0.0.0-dev, and only a build through
# this script replaces it in the artifact. A bare `mojo build` ships that
# placeholder, so this script is the one way to produce a versioned artifact.
#
# The bundled SQLite comes from SKILL_LOG_SQLITE when set — the pinned
# library scripts/package.sh fetched — else from this machine's system
# copy, which is the local gate's convenience and never the release's.
#
# Only src/ and vendor/ are built, and only the binary and its libraries
# are staged. The reference/ area is the verbatim report-era implementation
# kept as the parity ground truth: it is never built, never staged and
# never shipped in the release archive.
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(cd "$HERE/.." && pwd)"

BUILD="$ROOT/build"
DIST="$ROOT/dist"
VENDOR="$ROOT/vendor"
SRC="$ROOT/src"

# The generated source file: the version lives in the build, not in the
# checkout.
GENERATED="$BUILD/src/skill_log/version.mojo"

log() { printf '==> %s\n' "$*"; }

die() {
    printf 'build.sh: %s\n' "$*" >&2
    exit 1
}

# ---------------------------------------------------------------- version

resolve_version() {
    if [ -n "${SKILL_LOG_VERSION:-}" ]; then
        printf '%s' "$SKILL_LOG_VERSION"
        return
    fi
    # `git describe --tags` only: without a tag there is no release
    # version to bake in, and the fallback below is the honest answer.
    local described
    if described="$(git -C "$ROOT" describe --tags --dirty 2>/dev/null)" &&
        [ -n "$described" ]; then
        printf '%s' "$described"
        return
    fi
    printf '0.0.0-dev'
}

VERSION="$(resolve_version)"

# ------------------------------------------------------------------ build

log "version $VERSION"

rm -rf "$BUILD"
rm -rf "$DIST"
mkdir -p "$BUILD/src/skill_log" "$DIST/lib"

# The sources the build compiles: the tree under src/.
cp -r "$SRC/skill_log/." "$BUILD/src/skill_log/"

# The generated version module: the same shape as the checked-in
# placeholder, with the build's version baked in. It is written after the
# copy so it shadows the placeholder rather than being shadowed by it.
cat > "$GENERATED" <<EOF
"""The release version, baked in at build time.

Generated by scripts/build.sh. Do not edit: this file is rewritten on
every build, and the version it carries belongs to the build.
"""


def version() -> String:
    """The release version of this build."""
    return "$VERSION"
EOF

MOJO_BIN="$(mise x -- which mojo)"
log "mojo $("$MOJO_BIN" --version)"

"$MOJO_BIN" build -I "$VENDOR" -I "$BUILD/src" -o "$BUILD/skill-log" \
    "$BUILD/src/skill_log/main.mojo"

# ------------------------------------------------------- runtime libraries

# The Mojo runtime libraries are discovered from the built binary's
# DT_NEEDED graph, not from a hardcoded list: the direct dependency is
# libKGENCompilerRTShared.so, and the other two arrive through it.
#
# A library belongs to the bundle when it resolves inside the toolchain's
# own library directory. The system libraries (libc, libm, libstdc++, ...)
# are found in the loader's search path instead and are left alone.
mojo_lib_dir() {
    local mojo_bin mojo_root
    mojo_bin="$(readlink -f "$MOJO_BIN")"
    mojo_root="$(dirname "$mojo_bin")/../lib/python3.12/site-packages/modular/lib"
    [ -d "$mojo_root" ] || die "cannot find the Mojo runtime library directory at $mojo_root"
    printf '%s' "$mojo_root"
}

MOJO_LIB_DIR="$(mojo_lib_dir)"

# The sonames the binary needs, directly or through the runtime library.
bundle_sonames() {
    local binary="$1" lib_dir="$2"
    local seen="" soname path

    # The binary's own direct dependencies.
    for soname in $(readelf -d "$binary" | sed -n 's/.*(NEEDED).*\[\(.*\)\]$/\1/p'); do
        seen="$seen $soname"
    done

    # And the dependencies of every runtime library found so far.
    for soname in $seen; do
        path="$lib_dir/$soname"
        [ -f "$path" ] || continue
        for needed in $(readelf -d "$path" | sed -n 's/.*(NEEDED).*\[\(.*\)\]$/\1/p'); do
            case " $seen " in
            *" $needed "*) ;;
            *) seen="$seen $needed" ;;
            esac
        done
    done

    # Only the libraries the toolchain itself ships: the ones that live
    # in the Mojo library directory.
    for soname in $seen; do
        [ -f "$lib_dir/$soname" ] || continue
        printf '%s\n' "$soname"
    done
}

log "discovering the Mojo runtime libraries"
mapfile -t RUNTIME_LIBS < <(bundle_sonames "$BUILD/skill-log" "$MOJO_LIB_DIR")
[ "${#RUNTIME_LIBS[@]}" -gt 0 ] || die "no Mojo runtime libraries found in $MOJO_LIB_DIR"
for lib in "${RUNTIME_LIBS[@]}"; do
    log "  runtime library: $lib"
    cp "$MOJO_LIB_DIR/$lib" "$DIST/lib/"
done

# The SQLite library the vendored binding dlopens by soname. The real
# file behind the symlink is copied and named with the soname the loader
# asks for.
#
# A release never uses this machine's copy: scripts/package.sh supplies
# the fetched, pinned library through SKILL_LOG_SQLITE. The system
# library below is the local gate's convenience only — fine for
# scripts/test.sh, never what the release ships. A release build that
# cannot find its library fails here, loudly.
if [ -n "${SKILL_LOG_SQLITE:-}" ]; then
    SQLITE_SOURCE="$SKILL_LOG_SQLITE"
    [ -f "$SQLITE_SOURCE" ] ||
        die "SKILL_LOG_SQLITE names $SQLITE_SOURCE, which is not a file"
else
    SQLITE_SOURCE="$(readlink -f /usr/lib/libsqlite3.so.0 2>/dev/null || true)"
    [ -n "$SQLITE_SOURCE" ] && [ -f "$SQLITE_SOURCE" ] ||
        die "cannot find libsqlite3.so.0 on this machine"
fi
log "sqlite: $SQLITE_SOURCE"
cp "$SQLITE_SOURCE" "$DIST/lib/libsqlite3.so.0"

# ----------------------------------------------------------------- stage

cp "$BUILD/skill-log" "$DIST/skill-log"
chmod +x "$DIST/skill-log"

# The bundled libraries resolve through the binary's own directory, so the
# artifact carries no absolute path to this machine.
# shellcheck disable=SC2016  # $ORIGIN must reach patchelf literally
patchelf --set-rpath '$ORIGIN/lib' "$DIST/skill-log"

log "staged:"
log "  $DIST/skill-log"
for lib in "$DIST"/lib/*; do
    log "  $lib"
done
